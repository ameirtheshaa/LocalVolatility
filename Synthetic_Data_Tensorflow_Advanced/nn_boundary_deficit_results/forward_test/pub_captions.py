#!/usr/bin/env python3
r"""Emit the deck's figure captions as LaTeX macros, derived from pub_stats.json.

Every number that appears on a slide is computed here from the same JSON the figures
were drawn from, and the deck only ever cites a macro.  Nothing is typed by hand, so a
recomputation cannot leave a stale number behind in the text -- which is the usual way
a deck and its figures come to disagree.

Writes figures/forward_density/fd_numbers.tex, which the deck \input's.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUTDIR = os.path.join(os.path.dirname(os.path.dirname(HERE)), "presentation",
                      "figures", "forward_density")

# The raw 7 Aug 2001 file carries 421 rows (calls and puts, active and inactive).
# The calibration consumes the active calls only; load_quotes reports how many.
RAW_ROWS = 421


def main():
    st = json.load(open(os.path.join(HERE, "pub_stats.json")))
    taus = st["taus"]
    e, m, sw = st["f1_err"], st["f1_mass"], st["f1_sweep"]
    f3, dt = st["f3_rows"], st["f3_dt"]
    mom, w = st["f2_moments"], st["f2_window"]

    ours_sk = [o["skew_level"] for o in mom["ours"]]
    ours_sk_log = [o["skew_log"] for o in mom["ours"]]
    sd_short_gap = 100.0 * (f3[0]["sdA"] - f3[0]["sdB"]) / f3[0]["sdA"]
    neg_pct = 100.0 * max(x["neg_frac"] for x in m)
    min_f_pct = 100.0 * abs(min(x["min_f"] for x in m)) / max(x["peak"] for x in e)

    L = []
    A = L.append

    def cmd(name, val):
        A(rf"\newcommand{{\{name}}}{{{val}}}")

    A("% Auto-generated by pub_captions.py -- do not edit by hand.")
    A("% Every figure number cited in the deck resolves through one of these macros.")
    # ---- setup
    cmd("FDdate", "7 August 2001")
    cmd("FDspot", f"{st['S0']:,.2f}")
    cmd("FDrate", f"{100*st['r']:.0f}\\%")
    cmd("FDrawrows", f"{RAW_ROWS}")
    cmd("FDnquotes", f"{st['n_quotes']}")
    cmd("FDnmat", f"{len(taus)}")
    cmd("FDtaulo", f"{min(taus):.3f}")
    cmd("FDtauhi", f"{max(taus):.3f}")
    cmd("FDtaulist", ", ".join(f"{t:.3f}" for t in taus))
    cmd("FDKtrainlo", f"{st['K_train_lo']:,.0f}")
    cmd("FDKtrainhi", f"{st['K_train_hi']:,.0f}")
    cmd("FDKlo", f"{st['K_lo']:,.0f}")
    cmd("FDKhi", f"{st['K_hi']:,.0f}")
    # ---- fig 1
    cmd("FDhfd", f"{st['h_fd']:.0f}")
    cmd("FDhstar", f"{sw['h_star']:.0f}")
    cmd("FDslopeRound", f"{sw['slope_round']:+.2f}")
    cmd("FDslopeTrunc", f"{sw['slope_trunc']:+.2f}")
    cmd("FDsweepBest", f"{sw['best']:.1e}".replace("e-0", r"\times 10^{-") + "}")
    cmd("FDworstScale", f"{max(x['scale_max'] for x in e):.1e}"
        .replace("e-0", r"\times 10^{-") + "}")
    cmd("FDworstCoreMean", f"{max(x['core_mean'] for x in e):.1e}"
        .replace("e-0", r"\times 10^{-") + "}")
    cmd("FDpeakOverEnv", f"{max(x['peak_over_env'] for x in e):.0f}")
    cmd("FDmassWorst", f"{min(x['mass'] for x in m):.4f}")
    cmd("FDfwdErr", f"{max(abs(x['fwd_err_pct']) for x in m):.3f}\\%")
    cmd("FDnegPct", f"{neg_pct:.1f}\\%")
    cmd("FDminFpct", f"{min_f_pct:.2f}\\%")
    # ---- fig 2
    cmd("FDwinStart", w["start"])
    cmd("FDwinEnd", w["end"])
    cmd("FDwinN", f"{w['n']}")
    cmd("FDbandwidth", f"{st['f2_bandwidth']:.3f}")
    cmd("FDhisSkew", f"{mom['his']['skew_level']:+.2f}")
    cmd("FDhisSkewLog", f"{mom['his']['skew_log']:+.2f}")
    cmd("FDoursSkewLo", f"{min(ours_sk):+.2f}")
    cmd("FDoursSkewHi", f"{max(ours_sk):+.2f}")
    cmd("FDoursSkewLogLo", f"{min(ours_sk_log):+.2f}")
    cmd("FDoursSkewLogHi", f"{max(ours_sk_log):+.2f}")
    cmd("FDfairLevel", f"{st['f2_fair_spread']['level']:.2f}")
    cmd("FDfairLog", f"{st['f2_fair_spread']['log']:.2f}")
    cmd("FDfairRatio", f"{st['f2_fair_spread']['log']/st['f2_fair_spread']['level']:.0f}")
    cmd("FDmassFair", f"{min(st['f2_mass_fair']['k100'], st['f2_mass_fair']['k1000']):.4f}")
    # ---- fig 3
    cmd("FDmcPaths", f"{st['f3_mc']['M']:,}")
    cmd("FDmcSteps", f"{st['f3_mc']['n_steps']:,}")
    cmd("FDksWorst", f"{max(x['ks'] for x in f3):.4f}")
    cmd("FDksBest", f"{min(x['ks'] for x in f3):.4f}")
    cmd("FDlOneWorst", f"{max(x['dens_l1'] for x in f3):.4f}")
    cmd("FDivWorst", f"{100*max(x['iv_rmse'] for x in f3):.2f}")
    cmd("FDivRest", f"{100*max(x['iv_rmse'] for x in f3[1:]):.2f}")
    cmd("FDmartWorst", f"{max(abs(x['mart_err_pct']) for x in st['f3_mc']['martingale']):.3f}\\%")
    cmd("FDsdGapShort", f"{sd_short_gap:.1f}\\%")
    cmd("FDdtClosed", f"{dt['closed_pct']:.0f}\\%")
    cmd("FDdtRefine", f"{dt['refine']:.0f}")
    cmd("FDoutBandWorst", f"{100*max(x['out_of_band'] for x in f3):.0f}\\%")
    # ---- fig 2 (quote differencing)
    qq = st["f2_quotes"]
    cmd("FDqNegLo", f"{100*min(r['neg_frac'] for r in qq):.0f}\\%")
    cmd("FDqNegHi", f"{100*max(r['neg_frac'] for r in qq):.0f}\\%")
    cmd("FDqRatioLo", f"{min(r['peak_ratio'] for r in qq):.1f}")
    cmd("FDqRatioHi", f"{max(r['peak_ratio'] for r in qq):.1f}")
    cmd("FDqDKlo", f"{min(r['dK_min'] for r in qq):.0f}")
    cmd("FDqDKhi", f"{max(r['dK_max'] for r in qq):.0f}")
    cmd("FDqNegTot", f"{sum(r['n_neg'] for r in qq)}")
    cmd("FDqIntTot", f"{sum(r['n_interior'] for r in qq)}")

    # ---- fig 4
    cmd("FDnTauDense", f"{st['f4']['n_tau']}")

    os.makedirs(OUTDIR, exist_ok=True)
    p = os.path.join(OUTDIR, "fd_numbers.tex")
    with open(p, "w") as fh:
        fh.write("\n".join(L) + "\n")
    print(f"-> {p}  ({len(L)} macros)")
    for line in L[2:]:
        print("   " + line)


if __name__ == "__main__":
    main()
